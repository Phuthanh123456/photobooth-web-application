import { test, expect } from '@playwright/test';

test('operator and iPad display complete a real-time four-photo session', async ({ browser, page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('/operator');
  await expect(page.getByText('Connected', { exact: true })).toBeVisible();
  const displayContext = await browser.newContext({ viewport: { width: 1024, height: 768 }, isMobile: true, hasTouch: true });
  const display = await displayContext.newPage();
  display.on('pageerror', e => errors.push(e.message));
  await display.goto('/display');
  await expect(display.getByText('Connected', { exact: true })).toBeVisible();
  await expect(display.getByRole('button')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('operator-idle.png'), fullPage: true });
  await page.getByRole('button', { name: 'Start Session' }).click();
  await expect(display.locator('.countdown')).toHaveText('10');
  await expect(page.getByRole('button', { name: 'Start Session' })).toBeDisabled();
  await display.screenshot({ path: testInfo.outputPath('display-countdown.png'), fullPage: true });
  await display.reload();
  await expect(display.locator('.countdown')).toBeVisible();
  const started = Date.now();
  await expect(page.locator('.status-row h2')).toHaveText('COMPLETE', { timeout: 55_000 });
  expect(Date.now() - started).toBeGreaterThan(37_000);
  await expect(page.getByRole('img', { name: /Saved mock photo/ })).toHaveCount(4);
  await expect(display.getByText('All four photos are safely saved.')).toBeVisible();
  await expect(display.getByRole('img', { name: /Saved mock photo/ })).toHaveCount(4);
  const manifest = await page.request.get(`/images/${await page.locator('.session-id').innerText()}/manifest.json`);
  expect(manifest.ok()).toBe(true);
  expect(await manifest.json()).toMatchObject({ status: 'COMPLETE', captures: [ { status:'saved' }, { status:'saved' }, { status:'saved' }, { status:'saved' } ] });
  await page.getByRole('button', { name: 'Start Session' }).click();
  await expect(display.locator('.countdown')).toBeVisible();
  await page.getByRole('button', { name: 'Cancel Session' }).click();
  await expect(page.locator('.status-row h2')).toHaveText('CANCELLED');
  await expect(display.getByText('Session cancelled', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Acknowledge & reset' }).click();
  await expect(page.locator('.status-row h2')).toHaveText('IDLE');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('operator-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
  await displayContext.close();
});
