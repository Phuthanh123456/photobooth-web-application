import { test, expect } from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('operator and iPad display complete a real-time four-photo session', async ({ browser, page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto('/operator');
  await expect(page.getByText('Connected', { exact: true })).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollHeight - innerHeight)).toBeLessThanOrEqual(0);
  const displayContext = await browser.newContext({ viewport: { width: 1024, height: 768 }, isMobile: true, hasTouch: true });
  const display = await displayContext.newPage();
  display.on('pageerror', e => errors.push(e.message));
  await display.goto('/display');
  await expect(display.getByText('Connected', { exact: true })).toBeVisible();
  await expect(display.getByRole('button')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('operator-idle.png'), fullPage: true });
  await page.getByRole('button', { name: 'Start Session' }).click();
  await expect(display.locator('.countdown')).toHaveText('10');
  await expect(display.locator('.customer-preview')).toBeVisible();
  await expect(display.locator('.completed-display')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Start Session' })).toBeDisabled();
  await display.screenshot({ path: testInfo.outputPath('display-countdown.png'), fullPage: true });
  await display.reload();
  await expect(display.locator('.countdown')).toBeVisible();
  const started = Date.now();
  await expect(page.locator('.status-row h2')).toHaveText('COMPLETE', { timeout: 55_000 });
  expect(Date.now() - started).toBeGreaterThan(37_000);
  await expect(page.getByRole('img', { name: /Saved mock photo/ })).toHaveCount(4);
  await expect.poll(() => page.getByRole('img', { name: /Saved mock photo/ }).evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true);
  await expect(display.getByText('All four photos, together in your frame.')).toBeVisible();
  await expect(display.locator('.completed-display')).toBeVisible();
  await expect(display.locator('.customer-preview, .live-view, .customer-result')).toHaveCount(0);
  const finalStrip = display.getByRole('img', { name: 'Your four completed photos in the Frame CAP' });
  await expect(finalStrip).toBeVisible();
  await expect.poll(() => finalStrip.evaluate(image => (image as HTMLImageElement).naturalWidth > 0)).toBe(true);
  expect(await finalStrip.evaluate(image => (image as HTMLImageElement).naturalHeight)).toBeGreaterThan(1000);
  const manifest = await page.request.get(`/images/${await page.locator('.session-id').innerText()}/manifest.json`);
  expect(manifest.ok()).toBe(true);
  expect(await manifest.json()).toMatchObject({ status: 'COMPLETE', captures: [ { status:'saved' }, { status:'saved' }, { status:'saved' }, { status:'saved' } ] });
  const output = await page.request.get(await page.getByRole('link', {name:'Download JPG'}).getAttribute('href') ?? '');
  expect(output.ok()).toBe(true); expect((await output.body()).subarray(0,2)).toEqual(Buffer.from([255,216]));
  await expect(display.getByRole('img',{name:'Mã QR tải ảnh của lượt chụp này'})).toBeVisible();
  const guestUrl=await page.getByRole('link',{name:/Open guest photo download/}).getAttribute('href');
  expect(guestUrl).toMatch(/^http:\/\/localhost:5175\/s\/[A-Za-z0-9_-]{32}$/);
  const guest=await displayContext.newPage();await guest.setViewportSize({width:390,height:844});await guest.goto(guestUrl!);
  await expect(guest.getByRole('heading',{name:'Ảnh của bạn đã sẵn sàng'})).toBeVisible();
  await expect(guest.getByRole('img')).toBeVisible();
  const [download]=await Promise.all([guest.waitForEvent('download'),guest.getByRole('link',{name:'Tải ảnh JPG'}).click()]);
  expect(await readFile((await download.path())!)).toEqual(await output.body());
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await display.screenshot({path:testInfo.outputPath('display-qr-complete.png'),fullPage:true});
  await guest.screenshot({path:testInfo.outputPath('guest-download-mobile.png'),fullPage:true});
  await page.getByRole('button', { name: 'Start Session' }).click();
  await expect(display.locator('.countdown')).toBeVisible();
  await expect(display.locator('.session-qr')).toHaveCount(0);
  expect((await guest.request.get(`${guestUrl}/download`)).ok()).toBe(true);
  await page.getByRole('button', { name: 'Cancel Session' }).click();
  await expect(page.locator('.status-row h2')).toHaveText('CANCELLED');
  await expect(display.getByText('Session cancelled', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Acknowledge & reset' }).click();
  await expect(page.locator('.status-row h2')).toHaveText('IDLE');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('operator-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
  await displayContext.close();
});
